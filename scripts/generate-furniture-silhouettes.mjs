import sharp from "sharp";
import { readFile, writeFile } from "node:fs/promises";
// Run after changing furniture artwork or dimensions. Does not modify source images.
const definitions = await readFile(new URL("../src/game-data/homeFurniture.ts", import.meta.url), "utf8");
const samples = {};
for (const match of definitions.matchAll(/key: "([^"]+)".*?width: (\d+), height: (\d+)/g)) {
  const [, key, width, height] = match;
  const w = Number(width), h = Number(height);
  const asset = key.replace(/-2$/, "");
  const path = key === "indoor-kitchen" ? "kitchen/kitchen-interior-matched.png" : `home-interior/furniture/${asset}.png`;
  const { data, info } = await sharp(new URL(`../src/assets/sprite_assets/pngs/v2/isometric-test/${path}`, import.meta.url).pathname).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let left = info.width, top = info.height, right = -1, bottom = -1;
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
    if (data[(y * info.width + x) * 4 + 3] > 200) {
      left = Math.min(left, x); right = Math.max(right, x);
      top = Math.min(top, y); bottom = Math.max(bottom, y);
    }
  }
  const cw = right - left + 1, ch = bottom - top + 1;
  const scale = Math.min(w / cw, h / ch), ox = (w - cw * scale) / 2, oy = (h - ch * scale) / 2;
  samples[key] = [];
  for (let y = 1; y < 40; y += 2) for (let x = 1; x < 40; x += 2) {
    const px = Math.floor((x / 40 * w - ox) / scale) + left, py = Math.floor((y / 40 * h - oy) / scale) + top;
    if (px >= left && px <= right && py >= top && py <= bottom && data[(py * info.width + px) * 4 + 3] > 200) samples[key].push([x / 40, y / 40]);
  }
}
await writeFile(new URL("../src/game-data/homeFurnitureSilhouettes.ts", import.meta.url), `// Generated by scripts/generate-furniture-silhouettes.mjs; rerun after artwork/size changes.\nimport type { FurnitureKey } from "./homeFurniture";\nexport const FURNITURE_SILHOUETTES: Record<FurnitureKey, readonly (readonly [number, number])[]> = ${JSON.stringify(samples)};\n`);
